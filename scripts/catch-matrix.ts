/**
 * The catch matrix: proves the test suite would catch every planted bug.
 *
 *   1. Baseline: with no bugs on, every unit and E2E test must pass.
 *   2. For each bug: switch ONLY that bug on and run the suites again.
 *      At least one test must fail, otherwise the bug would ship unnoticed.
 *   3. Write docs/CATCH_MATRIX.md and exit 1 if any bug escaped.
 *
 * Usage:  npm run catch-matrix
 *         npm run catch-matrix -- --unit-only
 *         npm run catch-matrix -- --pw-config playwright.sandbox.config.ts
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { BUGS } from '../src/lib/bugs';

const args = process.argv.slice(2);
const unitOnly = args.includes('--unit-only');
const pwConfigIndex = args.indexOf('--pw-config');
const pwConfig = pwConfigIndex >= 0 ? args[pwConfigIndex + 1] : 'playwright.config.ts';
const TMP = '.catch-matrix';

interface RunResult {
  failed: string[];
  total: number;
}

function run(command: string, cmdArgs: string[], env: Record<string, string>) {
  return spawnSync(command, cmdArgs, {
    env: { ...process.env, ...env },
    encoding: 'utf8',
    shell: process.platform === 'win32',
    maxBuffer: 64 * 1024 * 1024,
  });
}

function unitRun(bugs: string): RunResult {
  const out = `${TMP}/unit-${bugs}.json`;
  run('npx', ['vitest', 'run', '--reporter=json', `--outputFile=${out}`], { BUGS: bugs });
  if (!existsSync(out)) throw new Error(`Vitest produced no report for BUGS=${bugs}`);
  const report = JSON.parse(readFileSync(out, 'utf8')) as {
    testResults: { assertionResults: { fullName: string; status: string }[] }[];
  };
  const all = report.testResults.flatMap((f) => f.assertionResults);
  return { failed: all.filter((a) => a.status === 'failed').map((a) => a.fullName), total: all.length };
}

interface PwSuite {
  title: string;
  specs?: { title: string; tests: { status: string }[] }[];
  suites?: PwSuite[];
}

function e2eRun(bugs: string): RunResult {
  const out = `${TMP}/e2e-${bugs}.json`;
  run('npx', ['playwright', 'test', '-c', pwConfig, '--project=chromium', '--reporter=json', '--retries=0'], {
    BUGS: bugs,
    PLAYWRIGHT_JSON_OUTPUT_NAME: out,
  });
  if (!existsSync(out)) throw new Error(`Playwright produced no report for BUGS=${bugs}`);
  const report = JSON.parse(readFileSync(out, 'utf8')) as { suites: PwSuite[] };
  const failed: string[] = [];
  let total = 0;
  const walk = (suite: PwSuite, path: string[]) => {
    const here = suite.title && !suite.title.endsWith('.ts') ? [...path, suite.title] : path;
    for (const spec of suite.specs ?? []) {
      for (const t of spec.tests) {
        total++;
        if (t.status === 'unexpected') failed.push([...here, spec.title].join(' › '));
      }
    }
    for (const child of suite.suites ?? []) walk(child, here);
  };
  report.suites.forEach((s) => walk(s, []));
  return { failed, total };
}

function main() {
  rmSync(TMP, { recursive: true, force: true });
  mkdirSync(TMP, { recursive: true });

  console.log('🧪 Baseline: no bugs on, everything must pass…');
  const baseUnit = unitRun('none');
  const baseE2e = unitOnly ? { failed: [], total: 0 } : e2eRun('none');
  if (baseUnit.failed.length || baseE2e.failed.length) {
    console.error('✖ The suite fails with no bugs on, so the matrix would mean nothing:');
    [...baseUnit.failed, ...baseE2e.failed].forEach((f) => console.error(`  - ${f}`));
    process.exit(1);
  }
  console.log(`   ✓ ${baseUnit.total} unit and ${baseE2e.total} E2E tests pass\n`);

  const rows = BUGS.map((bug, i) => {
    process.stdout.write(`🐞 ${String(i + 1).padStart(2)}. ${bug.title.padEnd(42)} `);
    const unit = unitRun(bug.id);
    const e2e = unitOnly ? { failed: [], total: 0 } : e2eRun(bug.id);
    const caught = unit.failed.length + e2e.failed.length > 0;
    console.log(caught ? `caught by ${unit.failed.length} unit + ${e2e.failed.length} E2E` : 'ESCAPED');
    return { bug, unit, e2e, caught };
  });

  const escaped = rows.filter((r) => !r.caught);
  const list = (names: string[]) =>
    names.length ? names.slice(0, 4).map((n) => `\`${n}\``).join('<br>') + (names.length > 4 ? `<br>…and ${names.length - 4} more` : '') : '–';

  const md = [
    '# Catch matrix',
    '',
    'Every planted bug, switched on **by itself**, and the tests that failed because of it.',
    'Generated by `npm run catch-matrix`. A bug with no failing test would fail the build.',
    '',
    `Baseline with no bugs on: **${baseUnit.total} unit** and **${baseE2e.total} E2E** (Chromium) tests, all passing.`,
    '',
    `**Result: ${rows.length - escaped.length} of ${rows.length} bugs caught.**`,
    '',
    '| # | Bug | Kind | Unit tests that fail | E2E tests that fail |',
    '|---|---|---|---|---|',
    ...rows.map((r, i) => `| ${i + 1} | ${r.bug.title} | ${r.bug.kind} | ${list(r.unit.failed)} | ${list(r.e2e.failed)} |`),
    '',
    '## Why two layers',
    '',
    'Nine bugs are caught by fast unit tests on the pricing rules. The keyboard bug lives only in the UI,',
    'so only a browser test (Tab to the button, press Enter) can catch it. The persistence bug is caught by',
    'both: a unit test with an in-memory storage, and an E2E test that really reloads the page.',
    '',
  ].join('\n');
  mkdirSync('docs', { recursive: true });
  writeFileSync('docs/CATCH_MATRIX.md', md);
  rmSync(TMP, { recursive: true, force: true });

  console.log(`\n${escaped.length ? '✖' : '✓'} ${rows.length - escaped.length}/${rows.length} bugs caught. Wrote docs/CATCH_MATRIX.md`);
  if (escaped.length) {
    escaped.forEach((r) => console.error(`  ESCAPED: ${r.bug.title}`));
    process.exit(1);
  }
}

main();
